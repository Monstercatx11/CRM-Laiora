'use client';
import { useCallback, useEffect, useRef, useState } from 'react';
import type { WhatsAppStatus } from '@/lib/whatsapp';

const labels: Record<WhatsAppStatus['state'], string> = {
  unconfigured: 'Server WhatsApp belum dipasang', disconnected: 'Belum terhubung', connecting: 'Menghubungkan…',
  awaiting_qr: 'Scan QR dari WhatsApp Business', qr_expired: 'QR kedaluwarsa', connected: 'WhatsApp terhubung',
  reconnecting: 'Menghubungkan kembali…', storage_error: 'Penyimpanan sesi perlu diperiksa', unavailable: 'Server WhatsApp tidak dapat dijangkau',
};
const descriptions: Record<string, string> = {
  logged_out: 'Perangkat sudah dikeluarkan dari WhatsApp. Hubungkan kembali untuk memindai QR baru.',
  reconnect_exhausted: 'Percobaan koneksi dihentikan. Periksa server dan jaringan, lalu coba hubungkan kembali.',
  storage_error: 'Sesi tidak dapat disimpan dengan aman. Operator perlu memeriksa disk dan memulai ulang server.',
  database_unavailable: 'Pencatatan database tertunda. Pesan tersimpan dalam antrean terenkripsi dan akan dicoba kembali.',
  bridge_unavailable: 'Periksa apakah server WhatsApp aktif dan konfigurasi koneksinya sudah benar.',
};

export function WhatsAppConnection() {
  const [status, setStatus] = useState<WhatsAppStatus | null>(null);
  const [busy, setBusy] = useState(false);
  const [notice, setNotice] = useState('');
  const mounted = useRef(false);
  const statusRef = useRef<WhatsAppStatus | null>(null);
  const inFlight = useRef(false);
  const aborter = useRef<AbortController | null>(null);
  const load = useCallback(async (action: 'status' | 'connect' | 'disconnect' = 'status') => {
    if (inFlight.current) return;
    inFlight.current = true;
    const controller = new AbortController();
    aborter.current = controller;
    const timer = setTimeout(() => controller.abort(), 16000);
    if (action !== 'status') setBusy(true);
    try {
      const response = await fetch(`/api/whatsapp/${action}`, { method: action === 'status' ? 'GET' : 'POST', cache: 'no-store', signal: controller.signal });
      const data = await response.json();
      if (!mounted.current) return;
      if (typeof data.configured === 'boolean' && Object.hasOwn(labels, data.state)) { statusRef.current=data; setStatus(data); setNotice(''); }
      else if (response.status === 401 || response.status === 403) { setNotice('Sesi login tidak tersedia. Muat ulang halaman dan masuk kembali.'); setStatus(previous=>previous?{...previous,qrDataUrl:undefined}:previous); }
      else setNotice('Status WhatsApp belum dapat dimuat. Coba kembali.');
    } catch {
      if (mounted.current) {
        setNotice('Koneksi ke server terputus. Coba perbarui status.');
        setStatus(previous => previous ? { ...previous, qrDataUrl: undefined } : previous);
      }
    } finally {
      clearTimeout(timer);
      inFlight.current = false;
      if (mounted.current) setBusy(false);
    }
  }, []);
  useEffect(() => {
    mounted.current = true;
    void load();
    const timer = setInterval(() => { if (!document.hidden && statusRef.current?.configured) void load(); }, 6000);
    return () => { mounted.current = false; clearInterval(timer); aborter.current?.abort(); };
  }, [load]);
  const active = status && ['connecting', 'awaiting_qr', 'connected', 'reconnecting'].includes(status.state);
  return <section className="panel" aria-labelledby="whatsapp-title" style={{ marginTop: 24 }}>
    <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', gap: 16, flexWrap: 'wrap' }}>
      <div><span className="eyebrow">Linked Devices</span><h2 id="whatsapp-title">WhatsApp Business</h2></div>
      <span className="badge" role="status">{status ? labels[status.state] : 'Memuat status…'}</span>
    </div>
    <p>Hubungkan akun bisnis melalui QR untuk mencatat percakapan pelanggan ke Tracking Chat. Pesan yang dikirim dari ponsel juga dicatat. Dashboard tidak mengirim balasan otomatis.</p>
    {status?.state === 'unconfigured' && <p className="message">Konektor QR tersedia sebagai opsi. Server WhatsApp dengan penyimpanan permanen perlu dipasang terlebih dahulu; proses Linked Devices tidak berjalan di Vercel.</p>}
    {status?.error && descriptions[status.error] && <p className="message" role="status">{descriptions[status.error]}</p>}
    {status?.qrDataUrl && <div style={{ padding: 16, border: '1px solid var(--line)', borderRadius: 12, width: 'fit-content', maxWidth: '100%', background: '#fff' }}>
      {/* Authenticated, temporary inline PNG generated by the bridge, never a remote image. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img src={status.qrDataUrl} alt="QR untuk menghubungkan perangkat WhatsApp Laiora" width={280} height={280} style={{ display: 'block', maxWidth: '100%', height: 'auto' }} />
      <p style={{ maxWidth: 280, fontSize: 13 }}>WhatsApp Business → Perangkat tertaut → Tautkan perangkat. QR hanya untuk admin akun ini.</p>
    </div>}
    {status?.state === 'qr_expired' && <p className="message">QR sudah kedaluwarsa. Tunggu QR diperbarui atau putuskan sesi lalu hubungkan kembali.</p>}
    <div style={{ display: 'flex', gap: 12, flexWrap: 'wrap', alignItems: 'center' }}>
      <button className="primary" style={{ width: 'auto' }} disabled={busy || !status?.configured || !!active || status?.state === 'storage_error'} onClick={() => void load('connect')}>{busy ? 'Memproses…' : 'Hubungkan WhatsApp'}</button>
      <button className="secondary" style={{ marginTop: 24, padding: '12px 18px', borderRadius: 7, border: '1px solid var(--line)', background: 'white' }} disabled={busy} onClick={() => void load()}>Perbarui status</button>
      {status?.configured && !['disconnected', 'unconfigured', 'unavailable'].includes(status.state) && <button className="secondary" style={{ marginTop: 24, padding: '12px 18px', borderRadius: 7, border: '1px solid var(--line)', background: 'white' }} disabled={busy} onClick={() => { if (window.confirm('Putuskan perangkat WhatsApp dashboard? Pencatatan chat akan berhenti sampai Anda menghubungkannya kembali.')) void load('disconnect'); }}>Putuskan perangkat</button>}
    </div>
    {notice && <p className="message error" role="alert">{notice}</p>}
    {status?.configured && <p className="footnote">Antrean pencatatan: {status.backlog ?? 0} pesan{status.lastMessageAt ? ` · Pesan terakhir diterima ${new Date(status.lastMessageAt).toLocaleString('id-ID', { timeZone: 'Asia/Jakarta' })} WIB` : ''}.</p>}
    <p className="footnote">Koneksi Linked Devices ini memakai library tidak resmi. Sesi dapat terputus, perlu dipindai ulang, atau dibatasi WhatsApp. Riwayat yang tersedia bergantung pada WhatsApp; gunakan ponsel untuk balasan dan lampiran.</p>
  </section>;
}
